/**
 * Build-time: turn the Latin "3" (Syne ExtraBold) and the Arabic "ع" (Cairo
 * Bold) into a precomputed morph.
 *
 * Why precomputed: SVG cannot interpolate between two `d` strings whose command
 * structures differ, and shipping a morph library to do it at runtime costs
 * more than the morph is worth. flubber runs HERE, offline, and the page ships
 * a plain array of path strings that one rAF loop steps through — one attribute
 * write per frame, no library, no parsing.
 *
 *   node scripts/build-morph.mjs
 */
import fs from 'node:fs'
import * as fontkit from 'fontkit'
import flubber from 'flubber'

const FRAMES = 30
const BOX = 100 // both glyphs are normalised into a 0..100 square

function glyphPath(file, variation, char) {
  const font = fontkit.openSync(file).getVariation(variation)
  const run = font.layout(char)
  const glyph = run.glyphs[0]
  const scale = BOX / font.unitsPerEm
  // fontkit's y axis points up and the origin is the baseline; SVG's points
  // down. Flip and translate so the glyph sits inside the box either way.
  const p = glyph.path.scale(scale, -scale)
  const b = p.bbox
  const w = b.maxX - b.minX
  const h = b.maxY - b.minY
  const k = (BOX * 0.86) / Math.max(w, h)
  return p
    .scale(k, k)
    .translate(-(b.minX * k) + (BOX - w * k) / 2, -(b.minY * k) + (BOX - h * k) / 2)
    .toSVG()
}

const three = glyphPath('/tmp/fonts/Syne.ttf', { wght: 800 }, '3')
const ain = glyphPath('/tmp/fonts/Cairo.ttf', { wght: 700 }, 'ع')

// maxSegmentLength keeps the in-between shapes smooth rather than letting long
// straight runs snap between keyframes.
// maxSegmentLength trades smoothness against payload. 1.2 subdivided the
// outlines so finely that the 40 frames came to 572 KB — in the HERO chunk,
// which is the LCP's critical path. 6 keeps the in-between shapes clean at the
// size this is rendered and costs an order of magnitude less.
const morph = flubber.interpolate(three, ain, { maxSegmentLength: 6 })

/** Two decimals is already sub-pixel at any size this renders at. */
const trim = (d) => d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n) * 10) / 10))

const frames = Array.from({ length: FRAMES }, (_, i) => trim(morph(i / (FRAMES - 1))))

const out = `/**
 * GENERATED by scripts/build-morph.mjs — do not edit by hand.
 *
 * ${FRAMES} frames morphing the Latin "3" (Syne ExtraBold) into the Arabic "ع"
 * (Cairo Bold), both normalised into a 0 0 ${BOX} ${BOX} viewBox.
 *
 * This is the page's one irreducible idea: in Arabizi the digit 3 IS the letter
 * ع, so Jou3an's 3 is simultaneously the letter in جوعان and the number of
 * answers. No competitor can run this animation.
 */
export const MORPH_VIEWBOX = '0 0 ${BOX} ${BOX}'
export const MORPH_FRAMES: readonly string[] = ${JSON.stringify(frames, null, 0)}
`
fs.writeFileSync('src/lib/threeAinMorph.ts', out)
const kb = (Buffer.byteLength(out) / 1024).toFixed(1)
console.log(`wrote src/lib/threeAinMorph.ts — ${FRAMES} frames, ${kb} KB`)
